#!/usr/bin/env bash

set -euo pipefail

usage() {
    cat <<'EOF'
Usage: bash clean_results.sh [options]

List or remove generated ActExchanger evaluation results. The script preserves
source files, datasets, pretrained checkpoints, and non-online training runs.
It performs a dry run by default; deletion requires --force.

Options:
  --dry-run             List candidates without deleting them (default).
  --force               Delete the listed candidates.
  --results-root PATH   Check PATH for online-training run directories.
                        Default: <repository>/ckpt, or $RESULTS_ROOT.
  --include-caches      Also remove Python bytecode/cache files.
  -h, --help            Show this help text.

Examples:
  bash clean_results.sh
  bash clean_results.sh --force
  bash clean_results.sh --results-root /home/Maniskill/ckpt --force
  bash clean_results.sh --include-caches --force
EOF
}

force=0
include_caches=0
results_root_arg="${RESULTS_ROOT:-}"

while [[ "$#" -gt 0 ]]; do
    case "$1" in
        --dry-run)
            force=0
            shift
            ;;
        --force)
            force=1
            shift
            ;;
        --include-caches)
            include_caches=1
            shift
            ;;
        --results-root)
            [[ "$#" -ge 2 ]] || {
                echo "--results-root requires a path." >&2
                exit 2
            }
            results_root_arg="$2"
            shift 2
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            echo "Unknown option: $1" >&2
            usage >&2
            exit 2
            ;;
    esac
done

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(git -C "$script_dir" rev-parse --show-toplevel 2>/dev/null)" || {
    echo "clean_results.sh must be located inside a Git worktree." >&2
    exit 2
}
repo_root="$(realpath -m "$repo_root")"
results_root="$(realpath -m "${results_root_arg:-$repo_root/ckpt}")"
if [[ "$results_root" == "/" || "$results_root" == "$repo_root" || "$results_root" == "${HOME:-__unset__}" ]]; then
    echo "Refusing unsafe results root: $results_root" >&2
    exit 2
fi

declare -a candidates=()
declare -A seen=()

is_under() {
    local path="$1"
    local parent="$2"
    [[ "$path" == "$parent"/* ]]
}

add_candidate() {
    local requested="$1"
    local path
    path="$(realpath -m "$requested")"
    [[ -e "$path" || -L "$path" ]] || return 0

    # Never admit a broad or unresolved deletion target. External paths are
    # accepted only beneath the explicitly selected results root.
    if [[ "$path" == "/" || "$path" == "$repo_root" || "$path" == "$results_root" || "$path" == "${HOME:-__unset__}" ]]; then
        echo "Refusing unsafe cleanup target: $path" >&2
        exit 2
    fi
    if ! is_under "$path" "$repo_root/tmp" \
        && ! is_under "$path" "$repo_root/eval" \
        && ! is_under "$path" "$results_root" \
        && ! is_under "$path" "$repo_root/api" \
        && ! is_under "$path" "$repo_root/train" \
        && ! is_under "$path" "$repo_root/ours"; then
        echo "Refusing cleanup target outside approved roots: $path" >&2
        exit 2
    fi
    [[ -z "${seen[$path]+x}" ]] || return 0
    seen["$path"]=1
    candidates+=("$path")
}

# Outputs generated by eval/run.sh and its sub-suites. These names mirror the
# default output paths in eval/ablation, eval/overhead, and eval/discussion.
if [[ -d "$repo_root/tmp" ]]; then
    while IFS= read -r -d '' path; do
        case "$(basename "$path")" in
            ablation.png|531_ablation.png|531_ablation.pdf|*_breakdown*.png|overhead_*.csv|overhead_*.json|overhead_*.png|discussion_*.csv|discussion_*.json|discussion_*.png|vla_vs_cnn_accuracy_*.png|*.launch.log|*.gpu_monitor.log)
                add_candidate "$path"
                ;;
        esac
    done < <(find "$repo_root/tmp" -maxdepth 1 -type f -print0)
    add_candidate "$repo_root/tmp/ablation_runs"
fi

# Accuracy scripts write their figures beside the plotting source by default.
while IFS= read -r -d '' path; do
    add_candidate "$path"
done < <(
    find "$repo_root/eval" -type f \( \
        -name online_rl_acc.png -o \
        -name online_rl_acc_true.png \
    \) -print0 2>/dev/null
)

# A run directory is removable only when it has a result marker and one of its
# path components explicitly identifies it as an online run. Pretraining/SFT
# directories under the same checkpoint root are deliberately not selected.
if [[ -d "$results_root" ]]; then
    while IFS= read -r -d '' marker; do
        run_dir="$(dirname "$marker")"
        relative="${run_dir#"$results_root"/}"
        case "/$relative/" in
            */*_online*/*)
                add_candidate "$run_dir"
                ;;
        esac
    done < <(
        find "$results_root" -type f \( \
            -name metrics.json -o \
            -name metrics_history.json -o \
            -name eval_metrics.json -o \
            -name latest_metrics.json -o \
            -name time_breakdown.json \
        \) -print0 2>/dev/null
    )
fi

if [[ "$include_caches" == "1" ]]; then
    while IFS= read -r -d '' path; do
        add_candidate "$path"
    done < <(
        find "$repo_root/api" "$repo_root/train" "$repo_root/ours" "$repo_root/eval" \
            -type d -name __pycache__ -prune -print0 2>/dev/null
    )
    while IFS= read -r -d '' path; do
        add_candidate "$path"
    done < <(
        find "$repo_root/api" "$repo_root/train" "$repo_root/ours" "$repo_root/eval" \
            -type d -name __pycache__ -prune -o \
            -type f \( -name '*.pyc' -o -name '*.pyo' \) -print0 2>/dev/null
    )
fi

if [[ "${#candidates[@]}" -eq 0 ]]; then
    echo "No generated result files found."
    exit 0
fi

echo "Generated result paths (${#candidates[@]}):"
for path in "${candidates[@]}"; do
    if is_under "$path" "$repo_root"; then
        display_path="${path#"$repo_root"/}"
    else
        display_path="$path"
    fi
    size="$(du -sh -- "$path" 2>/dev/null | cut -f1 || true)"
    printf '  %-8s %s\n' "${size:-?}" "$display_path"
done

if [[ "$force" != "1" ]]; then
    echo "Dry run only. Re-run with --force to delete these paths."
    exit 0
fi

for path in "${candidates[@]}"; do
    rm -rf -- "$path"
done

echo "Removed ${#candidates[@]} generated result/cache path(s)."
